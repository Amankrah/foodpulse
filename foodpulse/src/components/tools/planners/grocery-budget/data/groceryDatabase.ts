export function getItemsByCategory(category: string): GroceryItem[] {
  return groceryDatabase.filter((item) => item.category === category)
}

export function getItemsForDiet(dietId: string): GroceryItem[] {
  if (!dietId || dietId === 'balanced') return groceryDatabase
  return groceryDatabase.filter((item) => item.dietCompatibility.includes(dietId))
}
